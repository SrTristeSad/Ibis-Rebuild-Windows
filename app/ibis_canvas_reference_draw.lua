-- Desenho da janela de escolha de tamanho, sem acessar Store.
-- Base visual: tutorial publico oficial /chapter_03_03.png.
local M={}
local g
function M.panel(r,titleFont,smallFont)
    g=assert(love and love.graphics,'LÖVE necessario')
    g.push('all')
    g.setColor(.82,.83,.84,1)
    g.rectangle('fill',r.x,r.y,r.w,r.h)
    g.setColor(.17,.18,.19,1)
    g.rectangle('fill',r.x,r.y,r.w,41)
    g.setColor(.96,.96,.96,1)
    g.setFont(titleFont)
    g.printf('Nova tela',r.x+45,r.y+11,r.w-90,'center')
    g.setColor(.20,.21,.22,1)
    g.rectangle('fill',r.x+2,r.y+42,r.w-4,35)
    g.rectangle('fill',r.x+2,r.y+79,r.w-4,35)
    g.setColor(.58,.59,.61,1)
    g.setFont(smallFont)
    g.print('Pasta — indisponível nesta versão',r.x+19,r.y+52)
    g.print('Importar imagem — indisponível',r.x+19,r.y+88)
    g.setColor(.25,.26,.28,1)
    g.rectangle('fill',r.x+2,r.y+116,r.w-4,23)
    g.setColor(.97,.97,.97,1)
    g.print('Ilustração',r.x+13,r.y+120)
    g.setColor(.16,.18,.20,1)
    g.print('W',r.x+17,r.y+151)
    g.print('H',r.x+17,r.y+191)
    g.setColor(.35,.37,.39,1)
    g.print('Escolha um tamanho ou ajuste W / H',r.x+14,r.y+218)
    local close={x=r.x+r.w-40,y=r.y+3,w=35,h=35}
    g.setColor(.91,.24,.25,1)
    g.setLineWidth(2)
    g.line(close.x+10,close.y+9,close.x+25,close.y+24)
    g.line(close.x+25,close.y+9,close.x+10,close.y+24)
    g.pop()
end
function M.disabled(row,smallFont)
    g=assert(love and love.graphics,'LÖVE necessario')
    g.push('all')
    g.setColor(.75,.75,.75,1)
    g.rectangle('fill',row.x,row.y,row.w,row.h-2)
    g.setColor(.57,.57,.57,1)
    g.rectangle('line',row.x+.5,row.y+.5,row.w-1,row.h-3)
    g.setColor(.35,.36,.38,1)
    g.setFont(smallFont)
    g.print(row.item.name,row.x+50,row.y+10)
    g.printf(('%d × %d • indisponível'):format(
        row.item.w,row.item.h),
        row.x+row.w-209,row.y+10,198,'right')
    g.pop()
end
function M.heading(row,font)
    g=assert(love and love.graphics,'LÖVE necessario')
    g.push('all')
    g.setColor(.28,.29,.30,1)
    g.rectangle('fill',row.x,row.y,row.w,row.h)
    g.setColor(.96,.96,.96,1)
    g.setFont(font)
    g.print(row.item.name,row.x+10,row.y+4)
    g.pop()
end
function M.footer(r,font)
    g=assert(love and love.graphics,'LÖVE necessario')
    g.push('all')
    g.setColor(.26,.27,.29,1)
    g.rectangle('fill',r.x+2,r.y+r.h-82,r.w-4,1)
    g.setColor(.24,.26,.28,1)
    g.setFont(font)
    g.print('Nome',r.x+14,r.y+r.h-66)
    g.pop()
end
return M
