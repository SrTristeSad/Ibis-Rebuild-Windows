package.path = "app/?.lua;" .. package.path
local R = require('raster_lua')
assert(R.implementation=='lua' and R.load())
local function eq(a,b,msg) assert(a==b,(msg or 'mismatch')..': '..tostring(a)..' vs '..tostring(b)) end
local function alpha(b,x,y) return R.readPixel(b,x,y)%256 end
local b=R.buffer(64,48)
R.basicStroke(b,10.5,15.5,30.5,15.5,9,0x6d3abbff,0.4)
local a=alpha(b,15,15)
assert(a>0 and a<255, 'translucent brush missing')
eq(alpha(b,15,5),0,'outside stroke')
local before=R.bytes(b)
assert(not pcall(R.basicStroke,b,0,0,10,10,-1,0xff0000ff,1))
eq(R.bytes(b),before,'invalid brush must be atomic')
R.featherStroke(b,20.5,20.5,20.5,20.5,14,0xffffffff,0.75,0)
assert(alpha(b,26,20)>0,'soft edge missing')
local e=R.buffer(32,32)
R.basicStroke(e,16.5,16.5,16.5,16.5,11,0xff0000ff,1)
local full=alpha(e,16,16)
R.basicErase(e,16.5,16.5,16.5,16.5,9,0.5)
assert(alpha(e,16,16)<full,'eraser did not remove opacity')
local pressure=R.buffer(64,48)
R.pressureStroke(pressure,5.5,10.5,50.5,10.5,2,16,0xffffffff,
    0.2,1,1,0,0,0)
assert(alpha(pressure,46,10)>alpha(pressure,8,10),
    'interpolated pressure missing')
local tilted=R.buffer(64,48)
R.tiltStroke(tilted,26.5,25.5,26.5,25.5,16,0xffffffff,1,1,90,0)
assert(alpha(tilted,36,25)>0,'tilted major axis missing')
eq(alpha(tilted,26,35),0,'tilted minor axis too long')
local c=R.buffer(64,48)
local baseline=R.bytes(c)
local mask=R.strokeCoverage(c)
R.accumulatedStroke(c,baseline,mask,15.5,15.5,15.5,15.5,10,10,
    0x12a9c8ff,0.4,0.4,1,0,0,0)
local first=alpha(c,15,15)
R.accumulatedStroke(c,baseline,mask,8.5,15.5,24.5,15.5,10,10,
    0x12a9c8ff,0.4,0.4,1,0,0,0)
eq(alpha(c,15,15),first,'stroke darkened its own overlap')
local later=R.buffer(64,48,R.bytes(c))
R.accumulatedStroke(later,R.bytes(later),R.strokeCoverage(later),
    15.5,15.5,15.5,15.5,10,10,0x12a9c8ff,0.4,0.4,1,0,0,0)
assert(alpha(later,15,15)>first,'independent gestures must build opacity')
local er=R.buffer(64,48,R.bytes(later))
local erBase=R.bytes(er)
local erMask=R.strokeCoverage(er)
R.accumulatedStroke(er,erBase,erMask,15.5,15.5,15.5,15.5,10,10,
    0,0.5,0.5,1,0,0,2)
local erased=alpha(er,15,15)
assert(erased<alpha(later,15,15))
R.accumulatedStroke(er,erBase,erMask,8.5,15.5,24.5,15.5,10,10,
    0,0.5,0.5,1,0,0,2)
eq(alpha(er,15,15),erased,'eraser accumulated twice')
local f=R.buffer(2,2)
R.pixel(f,0,0,0xff0000ff)
R.pixel(f,1,1,0x0000ffff)
R.flip(f,0)
eq(R.readPixel(f,1,0),0xff0000ff)
R.flip(f,1)
eq(R.readPixel(f,0,0),0x0000ffff)
eq(R.pressure(0.5,true,0,1),0.5)
local n,ok=R.thickness(1,3)
eq(n,1)
assert(not ok)
local pack=R.pack({{id=1,info=2,x=4,y=7,pressure=0.8,stylus=true,azimuth=3}})
eq(#pack.ints,2)
eq(#pack.floats,7)
eq(#pack.times,1)
print('Lua stroke engine: hard, feather, tilt, pressure, accumulated opacity, eraser, flip OK')
