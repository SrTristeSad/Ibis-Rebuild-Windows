package.path = "app/?.lua;" .. package.path
local R = require("raster_lua")
assert(R.load() and R.available)
local a = R.buffer(4, 4)
assert(#R.bytes(a) == 64)
R.pixel(a, 1, 1, 0xff0000ff)
assert(R.readPixel(a, 1, 1) == 0xff0000ff)
local b = R.buffer(4, 4)
R.pixel(b, 1, 1, 0x0000ffff)
R.composite(a,b,0.5)
local mixed = R.readPixel(a,1,1)
assert(mixed ~= 0xff0000ff and mixed ~= 0x0000ffff)
local partial = R.regionBytes(a,{x=1,y=1,w=1,h=1})
assert(#partial == 4)
R.clearRect(a,{x=1,y=1,w=1,h=1})
assert(R.readPixel(a,1,1) == 0)
R.clear(a,0x11223344)
assert(R.readPixel(a,3,3) == 0x11223344)
print("Lua raster buffer/composition: OK")
