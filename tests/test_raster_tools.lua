package.path = 'app/?.lua;' .. package.path
local R=require('raster_lua')
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local b=R.buffer(16,16)
R.basicShape(b,2,2,9,9,0,true,1,0xff0000ff)
eq(R.readPixel(b,4,4),0xff0000ff)
eq(R.readPixel(b,1,1),0)
R.basicShape(b,0,0,15,15,1,false,2,0x00ff00ff)
assert(R.readPixel(b,8,0)~=0,'ellipse border absent')
local fill=R.buffer(4,4)
for y=0,3 do R.pixel(fill,1,y,0xffffffff) end
local count=R.bucketFill(fill,0,0,0xff0000ff,0)
eq(count,4)
eq(R.readPixel(fill,2,0),0)
eq(R.readPixel(fill,1,2),0xffffffff)
local before=R.bytes(fill)
assert(not pcall(R.bucketFill,fill,0,0,0,300))
eq(R.bytes(fill),before)
local move=R.buffer(4,4)
R.pixel(move,0,0,0xff0000ff)
R.moveRect(move,0,0,1,1,2,2)
eq(R.readPixel(move,0,0),0)
eq(R.readPixel(move,2,2),0xff0000ff)
R.moveRect(move,2,2,1,1,-4,0)
eq(R.readPixel(move,2,2),0)
local trans=R.buffer(3,3)
R.pixel(trans,0,0,0xff0000ff)
R.pixel(trans,1,0,0x00ff00ff)
R.transformRect(trans,0,0,2,1,0,0,1,2,1)
eq(R.readPixel(trans,0,0),0xff0000ff)
eq(R.readPixel(trans,0,1),0x00ff00ff)
local snapshot=R.bytes(trans)
assert(not pcall(R.transformRect,trans,0,0,1,1,2,2,2,2,0))
eq(R.bytes(trans),snapshot)
print('Lua tools: selection, transforms, bucket, geometry OK')
